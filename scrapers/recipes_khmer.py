COLUMNS = ["dish_id", "dish_name", "dish_name_kh", "search", "recipe_title", "description", "ingredients", "steps",
           "prep_minutes", "cook_minutes", "total_minutes", "servings", "calories_per_serving", "difficulty",
           "source", "source_url", "recipe_id"]


def difficulty(n_steps: int, total: int) -> str:     # same rule as scrapers/recipes_foodcom.py
    if n_steps <= 6 and total <= 45:
        return "easy"
    if n_steps >= 12 or total >= 120:
        return "hard"
    return "medium"


def rows() -> list:
    out = []
    for r in RECIPES:
        total = r["prep"] + r["cook"]
        out.append({"dish_id": r["dish_id"], "dish_name": r["dish_name"], "dish_name_kh": r["dish_name_kh"],
                    "search": r["search"], "recipe_title": r["recipe_title"], "description": r["description"],
                    "ingredients": json.dumps(r["ingredients"], ensure_ascii=False),
                    "steps": json.dumps(r["steps"], ensure_ascii=False),
                    "prep_minutes": r["prep"], "cook_minutes": r["cook"], "total_minutes": total,
                    "servings": r["servings"], "calories_per_serving": "", "difficulty": difficulty(len(r["steps"]), total),
                    "source": SOURCE, "source_url": "", "recipe_id": ""})
    return out


def merge_into(recipes_csv: Path, khmer_rows: list):
    """Replace the Khmer rows of data/recipes.csv (keeps every Food.com row)."""
    ids = {r["dish_id"] for r in khmer_rows}
    with recipes_csv.open(encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fields = list(reader.fieldnames)
        kept = [r for r in reader if r["dish_id"] not in ids]
    fields += [c for c in COLUMNS if c not in fields]
    with recipes_csv.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in kept + khmer_rows:
            w.writerow({k: r.get(k, "") for k in fields})
    return len(kept)


def main():
    khmer = rows()
    with OUT.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(khmer)
    kept = merge_into(RECIPES_CSV, khmer)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(khmer)} Khmer recipes); "
          f"{RECIPES_CSV.relative_to(ROOT)} now has {kept} Food.com + {len(khmer)} Khmer recipes")


if __name__ == "__main__":
    sys.exit(main())
